"""Turn authz.lock findings into runnable pytest regression tests in the target repo's own style,
then PROVE each test: it must pass on base and fail on head.

In the full product a Nemotron agent writes these tests and iterates in a sandbox until the
base-pass / head-fail proof holds. Here the tests come from 4 fixed patterns that cover the
finding shapes in the demo scenarios.
"""
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HEADER = '''# Generated by authz.lock from finding(s) in {scenario}. Proof: passes on base, fails on the PR.
from fastapi.testclient import TestClient
from sqlmodel import Session, select

from app.core.config import settings
from app.models import Item, User
from tests.utils.user import authentication_token_from_email, create_random_user
from tests.utils.utils import random_email

API = settings.API_V1_STR


def _victim_item(db: Session, canary: str) -> Item:
    owner = create_random_user(db)
    item = Item(title=f"private {{canary}}", description=canary, owner_id=owner.id)
    db.add(item)
    db.commit()
    db.refresh(item)
    return item
'''

PATTERNS = {
    # read-isolation on an object endpoint (IDOR)
    "idor": '''

def test_authz_{fn}_cannot_read_other_users_item(client: TestClient, db: Session) -> None:
    item = _victim_item(db, "cnry-{fn}")
    headers = authentication_token_from_email(client=client, email=random_email(), db=db)
    r = client.{method}(f"{{API}}{path_fmt}", headers=headers)
    assert r.status_code in (400, 401, 403, 404)
    assert "cnry-{fn}" not in r.text
''',
    # read-isolation on a collection/export endpoint
    "collection": '''

def test_authz_{fn}_does_not_include_other_users_items(client: TestClient, db: Session) -> None:
    _victim_item(db, "cnry-{fn}")
    headers = authentication_token_from_email(client=client, email=random_email(), db=db)
    r = client.{method}(f"{{API}}{path}", headers=headers)
    assert "cnry-{fn}" not in r.text
''',
    # numeric side channel: count must only cover the caller's own objects
    "count": '''

def test_authz_{fn}_count_only_covers_own_items(client: TestClient, db: Session) -> None:
    _victim_item(db, "cnry-{fn}")
    email = random_email()
    headers = authentication_token_from_email(client=client, email=email, db=db)
    r = client.{method}(f"{{API}}{path}", headers=headers)
    assert r.status_code == 200
    me = db.exec(select(User).where(User.email == email)).one()
    own = db.exec(select(Item).where(Item.owner_id == me.id)).all()
    assert r.json()["count"] == len(own)
''',
    # privilege escalation via mass assignment
    "privilege": '''

def test_authz_{fn}_cannot_self_escalate(client: TestClient, db: Session) -> None:
    email = random_email()
    headers = authentication_token_from_email(client=client, email=email, db=db)
    client.{method}(f"{{API}}{path}", headers=headers,
                 json={{"full_name": "x", "is_superuser": True, "is_active": True}})
    db.expire_all()
    me = db.exec(select(User).where(User.email == email)).one()
    assert me.is_superuser is False
''',
}


def pick_pattern(v: dict) -> str | None:
    op = v["op"]
    if v["rule"].startswith("I4"):
        return "privilege"
    if v["rule"].startswith("I1"):
        return "idor" if "{" in op else "collection"
    return None


def generate(diff: dict, scenario: str) -> str:
    chosen = {}
    for v in diff["new_violations"]:
        pat = pick_pattern(v)
        if pat and v["op"] not in chosen:
            chosen[v["op"]] = pat
    for c in diff["changes"]:  # count side channel shows up as a widened cell, not an invariant
        if c["class"] == "WIDENED" and (c["head"]["count"] or 0) > (c["base"]["count"] or 0):
            chosen.setdefault(c["cell"].split(" | ")[0], "count")
    body = HEADER.format(scenario=scenario)
    for op, pat in chosen.items():
        method, path = op.split(" ", 1)
        fn = re.sub(r"[^a-z0-9]+", "_", f"{method} {path}".lower()).strip("_")
        path_fmt = path.replace("{id}", "{item.id}")
        body += PATTERNS[pat].format(fn=fn, method=method.lower(), path=path, path_fmt=path_fmt)
    return body if chosen else ""


def run_tests(repo: Path, ref: str, test_src: str, env_file: Path, tag: str) -> dict:
    tree = Path(f"/tmp/authz_rt_{tag}")
    subprocess.run(["git", "-C", str(repo), "worktree", "remove", "--force", str(tree)], capture_output=True)
    subprocess.run(["git", "-C", str(repo), "worktree", "add", "--detach", str(tree), ref], check=True,
                   capture_output=True)
    shutil.copy(env_file, tree / ".env")
    (tree / ".venv").symlink_to(repo / ".venv")
    tdir = tree / "backend" / "tests" / "authz"
    tdir.mkdir(parents=True, exist_ok=True)
    (tdir / "__init__.py").write_text("")
    (tdir / "test_authz_regressions.py").write_text(test_src)
    db = f"authz_rt_{tag}"
    base_url = "postgresql://postgres@localhost:5432"
    subprocess.run(["psql", "-h", "localhost", "-U", "postgres", "-qc", f'DROP DATABASE IF EXISTS "{db}" WITH (FORCE)'])
    subprocess.run(["psql", "-h", "localhost", "-U", "postgres", "-qc", f'CREATE DATABASE "{db}"'], check=True)
    from authzlock import worker_env  # allowlisted env: generated tests never see API keys
    env = dict(worker_env(), DATABASE_URL=f"{base_url.replace('postgres@', 'postgres:x' + tag + '@')}/{db}")
    py = str(tree / ".venv" / "bin" / "python")
    backend = tree / "backend"
    subprocess.run([py, "-m", "alembic", "upgrade", "head"], cwd=backend, env=env, check=True, capture_output=True)
    p = subprocess.run([py, "-m", "pytest", "-q", "-p", "no:cacheprovider", "tests/authz"], cwd=backend, env=env,
                       capture_output=True, text=True)
    subprocess.run(["git", "-C", str(repo), "worktree", "remove", "--force", str(tree)], capture_output=True)
    subprocess.run(["psql", "-h", "localhost", "-U", "postgres", "-qc", f'DROP DATABASE IF EXISTS "{db}" WITH (FORCE)'])
    last = [ln for ln in p.stdout.strip().splitlines() if ln.strip()][-1] if p.stdout.strip() else p.stderr[-300:]
    return {"ref": ref, "exit": p.returncode, "summary": last}


if __name__ == "__main__":
    repo, results, env_file = Path(sys.argv[1]).resolve(), Path(sys.argv[2]), Path(sys.argv[3])
    proofs = []
    for dfile in sorted(results.glob("pr-*.diff.json")):
        ref = dfile.name.replace(".diff.json", "")
        d = json.loads(dfile.read_text())
        src = generate(d, ref)
        if not src:
            continue
        (results / f"{ref}.test_authz_regressions.py").write_text(src)
        on_base = run_tests(repo, "base", src, env_file, "b_" + ref.replace("-", "_"))
        on_head = run_tests(repo, ref, src, env_file, "h_" + ref.replace("-", "_"))
        proven = on_base["exit"] == 0 and on_head["exit"] != 0
        proofs.append({"scenario": ref, "tests": src.count("\ndef test_"), "on_base": on_base["summary"],
                       "on_head": on_head["summary"], "proven": proven})
        print(proofs[-1], flush=True)
    (results / "regression_proofs.json").write_text(json.dumps(proofs, indent=1))
